async function main() {
  const comps = await prisma.componentcatalog.findMany({ orderBy: { id: "asc" } });
  let updated = 0;
  const skipped = [];

  for (const comp of comps) {
    // 合并两批数据：RICH_EXTRA 仅有能力/价值字段，RICH 的同名字段优先
    const rich = { ...(RICH_EXTRA[comp.id] || {}), ...(RICH[comp.id] || {}) };
    if (!rich) {
      skipped.push(comp.id);
      continue;
    }
    const detail = (comp.detail && typeof comp.detail === "object" ? { ...comp.detail } : {}) || {};

    // 能力 / 价值 / 前后对比：仅在数据库为空时写入，不覆盖既有精选内容
    if (rich.caps && (!Array.isArray(detail.capabilities) || detail.capabilities.length === 0)) {
      detail.capabilities = rich.caps;
    }
    if (rich.vals && (!Array.isArray(detail.valueProps) || detail.valueProps.length === 0)) {
      detail.valueProps = rich.vals;
    }
    if (rich.ba && (!Array.isArray(detail.beforeAfter) || detail.beforeAfter.length === 0)) {
      detail.beforeAfter = rich.ba;
    }

    // visual 字段级合并：痛点 / 收获 / 类型 / 专项数据
    const visual = { ...(detail.visual && typeof detail.visual === "object" ? detail.visual : {}) };
    if (rich.pp) visual.painPoint = rich.pp;
    if (rich.gain) visual.gain = rich.gain;
    if (rich.kind) visual.kind = rich.kind;
    if (rich.title) visual.title = rich.title;
    if (rich.caption) visual.caption = rich.caption;
    if (rich.checks) visual.checks = rich.checks;
    detail.visual = visual;

    await prisma.componentcatalog.update({ where: { id: comp.id }, data: { detail } });

    // 表字段补全（仅空缺时，服务占位组件 C16 / C22 / C51 / C52 / C58 / C59 / C60）
    const patch = {};
    if (rich.contract && !comp.contract) patch.contract = rich.contract;
    if (rich.previewData) {
      const pd = comp.previewData && typeof comp.previewData === "object" ? comp.previewData : {};
      if (!pd.inputMock && !pd.outputMock) patch.previewData = rich.previewData;
    }
    if (rich.hint && !comp.hint) patch.hint = rich.hint;
    if (Object.keys(patch).length > 0) {
      await prisma.componentcatalog.update({ where: { id: comp.id }, data: patch });
    }

    updated++;
    console.log(`✔ ${comp.id} ${comp.name} 能力/价值/图表叙事已补全`);
  }

  console.log(`\n--- 完成：更新 ${updated} 个组件；未涉及：${skipped.join(", ") || "无"} ---`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
